/* ov024 .rodata: MobiClip run/level prefix table, format variant 1.
 *
 * 4096 packed prefix entries followed by 256 residue bytes. The decoder peeks
 * twelve bits of the bitstream, indexes the entries with them, and gets back
 * everything it needs in one halfword:
 *
 *     bits 0-3    total bits the code consumes, the coefficient sign included
 *     bits 4-8    level magnitude
 *     bits 9-14   run of zero coefficients before it
 *     bit  15     last-coefficient flag
 *
 * The residue bytes drive the level and run extension paths, which the decoder
 * takes when the twelve-bit lookup is not enough on its own.
 *
 * The delink cuts this one object into three symbols. The first two carry
 * entries 0 to 83; the third carries the remaining 4012 entries and the
 * residue bytes, so it is declared as the struct that shape describes.
 */
typedef unsigned short u16;
typedef unsigned char u8;

#define VLC(bits, level, run, last)     ((u16)((bits) | ((level) << 4) | ((run) << 9) | ((last) << 15)))


typedef struct {
    u16 entries[4012];   /* prefix entries 84 through 4095 */
    u8 residue[256];
} MobiClipVlcTail;

